// Builds tools/art_manifest.js (the asset list used by the Art Mapper) from ART_BRIEF.md + data.js.
// Run: node tools/build_manifest.js
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..');
const brief = fs.readFileSync(path.join(__dirname, 'ART_BRIEF.md'), 'utf8').split('\n');
const ctx = {}; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'data.js'), 'utf8') + '\nthis.PAPERS=PAPERS;this.EVENTS=EVENTS;', ctx);
const titles = {};
ctx.PAPERS.forEach(p => titles[p.id] = p.title); ctx.EVENTS.forEach(e => titles[e.id] = e.title);

// Subtle versions of the deceptive scenes (the game wants these to look like ordinary, legitimate policies)
const OVERRIDE = {
  ending_fooled: 'A PM in a suit proudly holding a green certificate with a rosette on the chest and a smile, standing at a desk; through the window behind there is a smoking factory and a field of dead saplings; a small magnifying glass lies unused on the desk.',
  clean_coal: 'A coal power station with newly fitted modern filter units and tidy fencing; a worker in hi-vis shakes hands with a manager in a suit; calm blue sky; a thin pale plume still rises from the chimneys.',
  gas_future: 'A modern gas power station beside a neat pipeline; a worker in hi-vis checks a valve with a tablet; orderly and pleasant; a faint heat-shimmer at one pipe joint.',
  hydrogen_hype: 'A modern white hydrogen plant with storage tanks and two engineers with tablets under a clean sky; a small gas pipeline feeds the plant on one side.',
  flight_offsets: 'A passenger jet at an airport gate with passengers boarding; a small leaf-shaped logo on the tail; calm scene; faint heat shimmer behind the engine.',
  cheap_offsets: 'A business meeting: a manager and an official shake hands over a certificate on a table; a factory with a chimney is visible through the window behind them.',
  tree_per_ticket: 'A festival ticket booth with a potted sapling and a ticket stub on the counter; at the far edge a field of small staked seedlings, a few of them brown.',
  summit_pledge: 'A formal summit stage with delegates signing a large document at a long table, invented generic flags behind them; sober and calm; one sleepy delegate at the far end.',
  mr_slick: 'Portrait of the INDUSTRY ADVISER: a trustworthy professional middle-aged man in a well-fitted navy suit with a lanyard, warm confident smile, neat short hair; warm grey backdrop; face centred.',
  pia_pollster: 'Portrait of the MEDIA ADVISER: a friendly young woman with a headset and a tablet, trendy hair, bubbly smile; soft pink backdrop; face centred.'
};

const out = [];
let folder = null, group = null;
for (const line of brief) {
  let m;
  if ((m = line.match(/^## (\w+) \(assets\/(\w+)\)/))) { folder = m[2]; group = m[1]; continue; }
  if ((m = line.match(/^### (.+)$/))) { group = m[1].trim(); continue; }
  if (!folder) continue;
  if ((m = line.match(/^- (\w+) : (.+)$/))) {
    const id = m[1];
    out.push({ id, folder, group: folder === 'papers' ? group : folder, title: titles[id] || id, scene: OVERRIDE[id] || m[2].replace(/\bGREENWASH\.\s*/i, '') });
  }
}
fs.writeFileSync(path.join(__dirname, 'art_manifest.js'), '// generated by tools/build_manifest.js\nconst ART_MANIFEST = ' + JSON.stringify(out, null, 1) + ';\n');
console.log(out.length, 'assets');
const ex = fs.existsSync(path.join(root, 'assets'));
